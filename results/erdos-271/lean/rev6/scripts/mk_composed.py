#!/usr/bin/env python3
"""Generate Composed.lean from the byte-exact checker inputs in <bundle_dir> (default: checker-bundles).
Each B-theorem is `theorem <name> :\n<statement> :=\n<proof>` with statement/proof inserted verbatim (only trailing
newlines stripped), inside `namespace ComposedC9`. The final statement C9 is derived from b9.statement.txt (its
conclusion after the single hypothesis), not from any sidecar. Run compose_check.py first (hash + matching check)."""
import hashlib,sys,os
D=sys.argv[1] if len(sys.argv)>1 else 'checker-bundles'
OUT=sys.argv[2] if len(sys.argv)>2 else 'Composed.lean'
names=['b1','b5','b6','b7','b8a','b8b','b9']
R=lambda n,k: open(os.path.join(D,f'{n}.{k}.txt'),encoding='utf-8').read()
def concl_after_one_hyp(stmt):
    assert stmt.startswith('(\n'); d=0
    for j,c in enumerate(stmt):
        if c=='(': d+=1
        elif c==')':
            d-=1
            if d==0: break
    rest=stmt[j+1:]; assert rest.startswith(' →\n'); return rest[3:]
out=['import Mathlib','',
 '-- Exact-bundle composition of the C* chain (generated by scripts/mk_composed.py from checker-bundles/).',
 '-- Each theorem is `theorem <name> :\\n<statement> :=\\n<proof>` with the checker-verified statement and proof',
 '-- inserted byte-for-byte (trailing newlines stripped), inside namespace ComposedC9. No other change.','',
 'namespace ComposedC9','']
for n in names:
    s,p=R(n,'statement'),R(n,'proof')
    out.append(f'-- {n}: statement sha256 {hashlib.sha256(s.encode()).hexdigest()}, proof sha256 {hashlib.sha256(p.encode()).hexdigest()}')
    out+=[f'theorem {n} :',s.rstrip('\n')+' :=',p.rstrip('\n'),'']
c9=concl_after_one_hyp(R('b9','statement')).strip('\n')
out+=['/-- The C* end-to-end statement (conclusion of B9), obtained by typed application of the seven checked bundles. -/',
      'theorem composed :',c9+' :=','  b9 (b8b (b8a b1 b5 (b7 b6)))','','end ComposedC9','','#print axioms ComposedC9.composed','']
open(OUT,'w',encoding='utf-8').write('\n'.join(out)); print('wrote',OUT)
